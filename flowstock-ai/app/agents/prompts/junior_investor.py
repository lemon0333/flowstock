RAG_CONTEXT_TEMPLATE = """[참고 자료 — 사이트 /learn 페이지에서 발췌]
{topics_block}

위 자료에 답이 있으면 자료를 활용해서 답해줘. 답에 자료를 그대로 옮기지 말고 주린이 톤으로 풀어서 설명.
자료에 없으면 일반 지식으로 답하되, 관련 토픽 페이지를 안내하면 좋아.
"""


def format_rag_context(topics: list) -> str:
    """top-k TopicHit 리스트 → 시스템 프롬프트에 주입할 텍스트."""
    if not topics:
        return ""
    blocks = []
    for t in topics:
        blocks.append(
            f"[{t.title}] ({t.audience}, /learn/{t.slug})\n"
            f"  요약: {t.one_liner}\n"
            f"  내용: {t.snippet}"
        )
    topics_block = "\n\n".join(blocks)
    return RAG_CONTEXT_TEMPLATE.format(topics_block=topics_block)
